export function findNationByIdOrAlias(query: string): Nation | undefined {
  if (!query) return undefined;
  const cleaned = query.trim().toLowerCase();
  return POPULAR_NATIONS.find(
    (n) =>
      n.id === cleaned ||
      n.name.toLowerCase() === cleaned ||
      n.englishName.toLowerCase() === cleaned ||
      n.aliases.some((a) => a.toLowerCase() === cleaned)
  );
}

export function getNationById(id: string): Nation | undefined {
  return POPULAR_NATIONS.find((n) => n.id === id);
}
